"""How the baseline, A and B hold up as the toss, the sensor and the gripper get worse.

A and B here are the versions with no free solve: both start on the baseline's plan,
A makes one charged correction and B keeps replanning.  results/approach_b.md says
why.  Each factor moves on its own around the nominal cell, and toss noise and sensor
noise also move together, always on the same tosses, so any two rows can be compared
in pairs.

    HEADLESS=1 python robustness.py

runs every cell and writes results/robustness.csv and results/robustness.md.  Text
above the marker in the .md is kept, so interpretation can live there.  Naming "report"
only rewrites the tables, and naming "repeat" runs the nominal cell again and compares it
with the saved rows.
"""

from dataclasses import dataclass
import math
from pathlib import Path
import sys

import numpy as np

import catch
import replan_trials
from replan_trials import ReplanConfig, ReplanResult
import sensing
import toss
import trials

N_TRIALS = trials.N_TRIALS
CSV_PATH = Path(__file__).parent / "results" / "robustness.csv"
REPORT_PATH = Path(__file__).parent / "results" / "robustness.md"
GENERATED_MARKER = "<!-- Everything below this line is generated by robustness.py. -->"

BASELINE, A, B = "open_loop", "one_correction", "replan_moving_start"
APPROACHES = {BASELINE: "baseline", A: "Approach A", B: "Approach B"}

NOMINAL = dict(sigma_p=sensing.SIGMA_P, sigma_lat=ReplanConfig.sigma_lat, sigma_vz=ReplanConfig.sigma_vz)
SIGMAS_P = (0.0, 0.002, 0.005, 0.010, 0.020)  # m
SIGMAS_LAT = (0.0, 0.01, 0.02, 0.04, 0.08)  # m/s
SIGMAS_VZ = (0.0, 0.02, 0.05)  # m/s
ASSUMED_LATENCY = 0.03  # s; sweeping the real latency with the trigger told each value would change nothing
LATENCIES = (0.0, 0.02, 0.03, 0.05)  # s

# Toss noise and sensor noise together: the same grid Approach A's window was chosen from.
CROSS_SIGMAS_P = (0.0, 0.002, 0.003, 0.005)  # m
CROSS_SIGMAS_LAT = (0.02, 0.04, 0.06)  # m/s


def cells(approaches, trial_numbers=range(N_TRIALS), **settings) -> list[ReplanConfig]:
    """These approaches at these settings.  The baseline ignores the sensor, so its
    sensor settings are the same in every row."""
    configs = []
    for approach in approaches:
        row = {**NOMINAL, **settings}
        if approach == BASELINE:
            row["sigma_p"] = 0.0
        configs += replan_trials.cell(approach, trial_numbers, **row)
    return configs


def _latency_settings(latency: float) -> dict:
    return {} if latency == trials.TrialConfig.latency else dict(latency=latency, assumed_latency=ASSUMED_LATENCY)


def grid() -> list[ReplanConfig]:
    configs = cells((BASELINE, A, B)) + cells((BASELINE, A, B), range(N_TRIALS, 2 * N_TRIALS))
    configs += cells((BASELINE, A, B), sigma_p=0.0, sigma_lat=0.0, sigma_vz=0.0)
    for sigma_p in SIGMAS_P:
        if sigma_p != NOMINAL["sigma_p"]:
            configs += cells((A, B), sigma_p=sigma_p)
    for sigma_lat in SIGMAS_LAT:
        if sigma_lat != NOMINAL["sigma_lat"]:
            configs += cells((BASELINE, A, B), sigma_lat=sigma_lat)
    for sigma_vz in SIGMAS_VZ:
        if sigma_vz != NOMINAL["sigma_vz"]:
            configs += cells((BASELINE, A, B), sigma_vz=sigma_vz)
    for latency in LATENCIES:
        if latency != trials.TrialConfig.latency:
            configs += cells((BASELINE, A, B), **_latency_settings(latency))
    configs += cells((A, B), obs_mode=sensing.POSITION_AND_VELOCITY)
    configs += cells((BASELINE,), sigma_lat=0.06)
    for sigma_lat in CROSS_SIGMAS_LAT:
        for sigma_p in CROSS_SIGMAS_P:
            config = ReplanConfig(A, sigma_p=sigma_p, sigma_lat=sigma_lat, sigma_vz=NOMINAL["sigma_vz"])
            if config not in configs:
                configs += cells((A, B), sigma_p=sigma_p, sigma_lat=sigma_lat)
    return configs


@dataclass
class Row:
    """One approach at one setting."""

    results: list[ReplanResult]

    @property
    def caught(self) -> int:
        return sum(r.caught for r in self.results)

    def text(self) -> str:
        return trials._rate(self.caught, len(self.results))

    def paired(self, other: "Row") -> str:
        theirs = {r.trial: r.caught for r in other.results}
        only_this, only_other, p = trials.mcnemar([r.caught for r in self.results], [theirs[r.trial] for r in self.results])
        return f"{only_this} / {only_other}, p = {p:.2g}"


def select(results, approach, trial_set=0, **settings) -> Row:
    """The rows of one cell.  Settings left out are the nominal ones."""
    wanted = {**NOMINAL, "obs_mode": sensing.POSITION_ONLY, "latency": trials.TrialConfig.latency, **settings}
    if approach == BASELINE:
        wanted["sigma_p"] = 0.0
    return Row([r for r in results if r.approach == approach and r.trial // N_TRIALS == trial_set
                and all(getattr(r, name) == value for name, value in wanted.items())])


def factor_table(results, name: str, levels, setting: str, format_level, approaches=(BASELINE, A, B), settings_of=None) -> list[str]:
    """Caught, and the details that explain it, at each level of one factor."""
    settings_of = settings_of or (lambda level: {setting: level})
    lines = [f"| {name} | baseline caught | A caught | B caught | B against A: only B / only A, p | on pad, A / B | "
             "contact, A / B | stayed on the baseline's plan, A / B | failed solves per trial, B | predicted miss, median, A / B (cm) | "
             "timing error, 1 sigma, A / B (ms) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for level in levels:
        settings = settings_of(level)
        base = select(results, BASELINE, **settings) if BASELINE in approaches else None
        a, b = select(results, A, **settings), select(results, B, **settings)
        lines.append(
            f"| {format_level(level)} | {base.text() if base and base.results else '-'} | {a.text()} | {b.text()} | {b.paired(a)} "
            f"| {sum(r.caught_on_pad for r in a.results)} / {sum(r.caught_on_pad for r in b.results)} "
            f"| {sum(r.contact for r in a.results)} / {sum(r.contact for r in b.results)} "
            f"| {_on_baselines_plan(a)} / {_on_baselines_plan(b)} "
            f"| {np.mean([r.solve_failures for r in b.results]):.1f} "
            f"| {_median_cm(a)} / {_median_cm(b)} | {_timing_ms(a)} / {_timing_ms(b)} |")
    return lines


def _on_baselines_plan(row: Row) -> int:
    """How many tosses never left the baseline's plan, because every solve failed or nothing needed correcting."""
    return sum(r.plans_adopted <= 1 for r in row.results)


def _median_cm(row: Row) -> str:
    return f"{100 * np.nanmedian([r.predicted_miss for r in row.results]):.1f}"


def _timing_ms(row: Row) -> str:
    return f"{1e3 * np.nanstd([r.timing_error for r in row.results]):.1f}"


def cross_table(results) -> list[str]:
    """Toss noise and sensor noise together."""
    lines = ["| sigma lateral (m/s) | sigma_p (mm) | baseline caught | A caught | B caught | B against A: only B / only A, p |",
             "|---|---|---|---|---|---|"]
    for sigma_lat in CROSS_SIGMAS_LAT:
        for sigma_p in CROSS_SIGMAS_P:
            base = select(results, BASELINE, sigma_lat=sigma_lat)
            a, b = (select(results, approach, sigma_lat=sigma_lat, sigma_p=sigma_p) for approach in (A, B))
            lines.append(f"| {sigma_lat} | {1e3 * sigma_p:.0f} | {base.text()} | {a.text()} | {b.text()} | {b.paired(a)} |")
    return lines


def movement_needed(results: list[ReplanResult]) -> np.ndarray:
    """How far, in m, the pinch point has to go from where the brake leaves it to where
    this toss really comes down: the proposal's "movement needed from ball release to catch"."""
    plan = toss.plan_toss(catch.shared_kinematics().plant)
    start = catch.shared_kinematics().pinch(plan.q_traj.value(plan.t_release + toss.BRAKE).ravel())
    z_catch = plan.p_release[2] - toss.CATCH_DROP
    needed = []
    for r in results:
        p0 = np.array([r.p_release_true_x, r.p_release_true_y, r.p_release_true_z])
        v0 = np.array([r.v_release_true_x, r.v_release_true_y, r.v_release_true_z])
        needed.append(np.linalg.norm(toss.ballistic_position(p0, v0, toss.time_to_height(p0, v0, z_catch)) - start))
    return np.array(needed)


def movement_table(results) -> list[str]:
    """Catches against how far the arm has to go, at the nominal cell: the same tosses, split into four equal groups."""
    rows = {approach: select(results, approach).results for approach in APPROACHES}
    if not all(rows.values()):
        return []
    needed = movement_needed(rows[A])
    order = np.argsort(needed)
    lines = ["| movement needed (cm) | tosses | baseline caught | A caught | B caught |", "|---|---|---|---|---|"]
    by_trial = {approach: {r.trial: r for r in group} for approach, group in rows.items()}
    for part in (part for part in np.array_split(order, 4) if len(part)):
        tosses = [rows[A][i].trial for i in part]
        counts = " | ".join(str(sum(by_trial[approach][t].caught for t in tosses)) for approach in APPROACHES)
        lines.append(f"| {100 * needed[part[0]]:.1f} to {100 * needed[part[-1]]:.1f} | {len(part)} | {counts} |")
    return lines


def metric_table(results) -> list[str]:
    """Every metric on the final list, at the nominal cell."""
    lines = ["| metric | baseline | A | B |", "|---|---|---|---|"]
    rows = [select(results, approach).results for approach in APPROACHES]

    def add(name, value):
        lines.append(f"| {name} | " + " | ".join(value(group) for group in rows) + " |")

    def spread(column, scale, digits=2):
        def value(group):
            moved = [getattr(r, column) for r in group if r.solve_ok and not math.isnan(getattr(r, column))]
            return f"{scale * np.median(moved):.{digits}f}" if moved else "-"
        return value

    add("Caught (primary)", lambda g: trials._rate(sum(r.caught for r in g), len(g)))
    add("Contact", lambda g: f"{sum(r.contact for r in g)}")
    add("Caught on the pad", lambda g: f"{sum(r.caught_on_pad for r in g)}")
    add(f"Caught within {trials.SPEED_TOLERANCE}x of rated speed", lambda g: f"{sum(r.caught and r.peak_speed <= trials.SPEED_TOLERANCE for r in g)}")
    add("Predicted miss, median (cm)", spread("predicted_miss", 100))
    add("Timing error, 1 sigma (ms)", lambda g: f"{1e3 * np.nanstd([r.timing_error for r in g]):.1f}")
    add("Plan stop error, median (cm)", spread("plan_stop_error", 100))
    add("Tracking error, median (cm)", spread("tracking_error", 100))
    add("Peak speed, worst (of rated)", lambda g: f"{max((r.peak_speed for r in g if r.solve_ok), default=math.nan):.2f}")
    add("Solves, median", lambda g: f"{np.median([r.n_solves for r in g]):.0f}")
    add("Failed solves, total", lambda g: f"{sum(r.solve_failures for r in g)}")
    add("Target moved, median (cm)", spread("plan_drift", 100))
    add("Close decision moved, median (ms)", lambda g: "-" if all(math.isnan(r.trigger_shift) for r in g) else f"{1e3 * np.nanmedian([abs(r.trigger_shift) for r in g]):.1f}")
    return lines


def write_report(results: list[ReplanResult], path: Path) -> None:
    """Write the tables below the marker in path, keeping whatever is above it."""
    above = "# How the approaches hold up\n\n"
    if path.exists():
        above = path.read_text().split(GENERATED_MARKER)[0]
    mm = lambda level: f"{1e3 * level:.0f} mm"
    speed = lambda level: f"{level} m/s"
    sections = [
        ("Every metric on the final list, at the nominal cell", metric_table(results)),
        ("Sensor noise", factor_table(results, "sigma_p", SIGMAS_P, "sigma_p", mm)),
        ("Lateral toss noise", factor_table(results, "sigma lateral", SIGMAS_LAT, "sigma_lat", speed)),
        ("Vertical toss noise", factor_table(results, "sigma vertical", SIGMAS_VZ, "sigma_vz", speed)),
        (f"Close latency, with the trigger assuming {1e3 * ASSUMED_LATENCY:.0f} ms",
         factor_table(results, "real latency", LATENCIES, "latency", lambda level: f"{1e3 * level:.0f} ms")),
        ("Position and velocity sensing", factor_table(results, "observations", (sensing.POSITION_ONLY, sensing.POSITION_AND_VELOCITY), "obs_mode",
                                                       str, approaches=(A, B))),
        ("No noise at all", factor_table(results, "noise", ("none",), "", str,
                                         settings_of=lambda level: dict(sigma_p=0.0, sigma_lat=0.0, sigma_vz=0.0))),
        ("Tosses the nominal cell wasn't chosen from, trials 100 to 199", _fresh_table(results)),
        ("Toss noise and sensor noise together", cross_table(results)),
        ("Catches against how far the arm has to go, at the nominal cell", movement_table(results)),
    ]
    lines = [GENERATED_MARKER, "",
             "Every row is 100 tosses, position-only with 30 ms of close latency unless it says otherwise, at sigma_p = 2 mm, sigma lateral = 0.04 m/s and "
             "sigma vertical = 0.02 m/s except for what the table varies.  Caught is spec section 13.3's definition, with a 95% confidence interval.", ""]
    for title, table in sections:
        lines += [f"## {title}", ""] + table + [""]
    wall = [r.wall_time for r in results]
    lines += [f"{len(results)} trials, {np.mean(wall):.1f} s per trial on average per worker.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(above + "\n".join(lines))


def _fresh_table(results) -> list[str]:
    base, a, b = (select(results, approach, trial_set=1) for approach in APPROACHES)
    return ["| baseline caught | A caught | B caught | B against A: only B / only A, p |", "|---|---|---|---|",
            f"| {base.text()} | {a.text()} | {b.text()} | {b.paired(a)} |"]


def run():
    results = trials.sweep(grid(), runner=replan_trials.run_trial)
    trials.write_csv(results, CSV_PATH)
    print(f"{len(results)} trials written to {CSV_PATH}", flush=True)
    write_report(results, REPORT_PATH)


def repeat():
    """Re-run the nominal cell for A and B."""
    configs = cells((A, B))
    differences = trials.repeat_check(configs, CSV_PATH, runner=replan_trials.run_trial)
    print("\n".join([f"{len(differences)} differences from {CSV_PATH}"] + differences))


if __name__ == "__main__":
    if sys.argv[1:] == ["report"]:
        write_report(replan_trials.read_results(CSV_PATH), REPORT_PATH)
    elif sys.argv[1:] == ["repeat"]:
        repeat()
    else:
        run()
