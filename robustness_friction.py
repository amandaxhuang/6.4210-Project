"""The friction sweep: robustness.py's design, with the ball's material as the factor.

NEW FILE (friction sweep).  robustness.py, replan_trials.py and their results are
untouched; this writes its own results/friction.csv and results/friction.md.

The design matches the robustness sweep: every material runs the same 100 seeded
tosses (trials 0-99) through the baseline, Approach A and Approach B, at the nominal
noise (sigma_p 2 mm, sigma lateral 0.04 m/s, sigma vertical 0.02 m/s, 30 ms close
latency), so trial n is the same toss, sensor noise and gripper under every material
and every approach.  Only the ball-pad friction changes (environment_friction.py).
Everything is calibrated on the rubber ball, as before: the friction rows ask what
happens when the robot is handed a ball it wasn't tuned for.

Each material also gets one noise-free toss per approach (with no noise every trial
is the same toss, so one is enough): a quick check of whether a perfect catch still
holds before reading the noisy results.

    python robustness_friction.py pilot   # only the noise-free tosses: 12 trials, about a minute
    python robustness_friction.py quick   # 5 tosses per cell into results/friction_quick.*: a smoke test
    python robustness_friction.py         # everything not already in results/friction.csv (about 20 min)
    python robustness_friction.py report  # rewrite results/friction.md from the csv, no simulation
    python robustness_friction.py check   # rubber rows against results/robustness.csv's nominal cell

Every run keeps the rows already saved and runs only what's missing, so an
interrupted sweep picks up where it stopped.
"""

from dataclasses import asdict, dataclass, fields
import os
from pathlib import Path
import sys

# A sweep has nobody watching it.  Set before anything imports utils.viz, which reads
# it once, so you don't need HEADLESS=1 on the command line (robustness.py does).
os.environ.setdefault("HEADLESS", "1")

import numpy as np

import environment_friction as ef
import replan_trials
from replan_trials import ReplanConfig, ReplanResult
import robustness
from robustness import A, APPROACHES, B, BASELINE, NOMINAL, Row
import trials

N_TRIALS = trials.N_TRIALS
QUICK_TRIALS = 5
RESULTS = Path(__file__).parent / "results"
CSV_PATH = RESULTS / "friction.csv"
REPORT_PATH = RESULTS / "friction.md"
QUICK_CSV_PATH = RESULTS / "friction_quick.csv"
QUICK_REPORT_PATH = RESULTS / "friction_quick.md"
GENERATED_MARKER = "<!-- Everything below this line is generated by robustness_friction.py. -->"

MATERIALS = ef.MATERIALS  # name -> ball-pad coefficient
FRICTIONS = tuple(MATERIALS.values())
NAME_OF = {mu: name for name, mu in MATERIALS.items()}
RUBBER = ef.DEFAULT  # the reference: what every earlier result used
NO_NOISE = dict(sigma_p=0.0, sigma_lat=0.0, sigma_vz=0.0)


# NEW: robustness.py's trial settings and saved row, each with a friction column.
@dataclass(frozen=True)
class FrictionConfig(ReplanConfig):
    friction: float = RUBBER  # ball-pad coefficient


@dataclass
class FrictionResult(ReplanResult):
    friction: float = RUBBER


def run_trial(config: FrictionConfig) -> FrictionResult:
    """replan_trials.run_trial with the ball's friction set first.  Set on every trial
    because a sweep worker runs many trials, of different materials, in one process."""
    ef.set_friction(config.friction)
    result = replan_trials.run_trial(config)
    return FrictionResult(**asdict(result), friction=config.friction)


def cells(approaches, trial_numbers, friction: float, **settings) -> list[FrictionConfig]:
    """These approaches on these tosses with this ball, at the nominal noise unless
    settings say otherwise.  Same as robustness.cells: the baseline ignores the sensor."""
    configs = []
    for approach in approaches:
        row = {**NOMINAL, **settings}
        if approach == BASELINE:
            row["sigma_p"] = 0.0
        configs += [FrictionConfig(approach, trial=t, friction=friction, **row) for t in trial_numbers]
    return configs


def pilot_grid() -> list[FrictionConfig]:
    """One noise-free toss per material and approach."""
    return [c for mu in FRICTIONS for c in cells((BASELINE, A, B), [0], mu, **NO_NOISE)]


def grid(n_trials: int = N_TRIALS) -> list[FrictionConfig]:
    """The noise-free checks, then every material at the nominal noise."""
    return pilot_grid() + [c for mu in FRICTIONS for c in cells((BASELINE, A, B), range(n_trials), mu)]


def read_results(path: Path) -> list[FrictionResult]:
    """The saved rows.  Same parsing as replan_trials.read_results, into FrictionResult."""
    def value(field, cell):
        if field.type is bool:
            return cell == "True"
        if field.type is str:
            return cell
        if cell == "None":
            return None
        return int(cell) if field.type is int else float(cell)

    if not path.exists():
        return []
    return [FrictionResult(**{f.name: value(f, row[f.name]) for f in fields(FrictionResult) if f.name in row})
            for row in trials.read_csv(path)]


def _settings(trial) -> tuple:
    """Everything that makes a trial what it is, from its config or its saved row."""
    return tuple(getattr(trial, f.name) for f in fields(FrictionConfig))


def run(configs: list[FrictionConfig], csv_path: Path = CSV_PATH, report_path: Path = REPORT_PATH) -> list[FrictionResult]:
    """Run whichever of configs aren't saved yet, then save everything in a fixed order."""
    saved = {_settings(r): r for r in read_results(csv_path)}
    new = [c for c in configs if _settings(c) not in saved]
    print(f"{len(new)} trials to run, {len(configs) - len(new)} already saved in {csv_path}", flush=True)
    if new:
        saved.update(zip(map(_settings, new), trials.sweep(new, runner=run_trial)))
    order = {key: i for i, key in enumerate(map(_settings, grid() + configs))}
    results = sorted(saved.values(), key=lambda r: order.get(_settings(r), len(order)))
    trials.write_csv(results, csv_path)
    write_report(results, report_path)
    print(f"{len(results)} trials in {csv_path}; report in {report_path}", flush=True)
    return results


# ---------- picking rows out ----------

def select(results, approach: str, friction: float, noisy: bool = True) -> Row:
    """One approach with one ball: the 100 nominal-noise tosses, or the noise-free one."""
    want = NOMINAL if noisy else NO_NOISE
    keep = []
    for r in results:
        if r.approach != approach or r.friction != friction:
            continue
        settings = {**want, "sigma_p": 0.0} if approach == BASELINE else want
        if all(getattr(r, name) == value for name, value in settings.items()):
            keep.append(r)
    return Row(keep)


def outcome(r) -> str:
    """How one toss ended, from columns every row already has:
    caught; gripped, then lost (the fingers closed on it and held, but for under
    catch.HOLD_TIME: the slippery-ball failure); touched, never held (hit the hand
    but was never gripped); or no contact."""
    if r.caught:
        return "caught"
    if r.hold_time > 0:
        return "gripped, then lost"
    if r.contact:
        return "touched, never held"
    return "no contact"


OUTCOMES = ("caught", "gripped, then lost", "touched, never held", "no contact")


def outcome_counts(row: Row) -> dict[str, int]:
    counts = dict.fromkeys(OUTCOMES, 0)
    for r in row.results:
        counts[outcome(r)] += 1
    return counts


def against_rubber(results, approach: str, friction: float) -> str:
    """Same approach, same tosses, this ball against the rubber one: how many catches
    only rubber made (lost) and only this ball made (gained), with McNemar's p."""
    this, rubber = select(results, approach, friction), select(results, approach, RUBBER)
    caught_rubber = {r.trial: r.caught for r in rubber.results}
    pairs = [(r.caught, caught_rubber[r.trial]) for r in this.results if r.trial in caught_rubber]
    if not pairs:
        return "-"
    gained, lost, p = trials.mcnemar([a for a, _ in pairs], [b for _, b in pairs])
    return f"{lost} / {gained}, p = {p:.2g}"


def release_change(results, friction: float) -> str:
    """How much this ball changed the toss itself: the median and largest change in
    the ball's release velocity against the rubber ball on the same toss (cm/s).
    The arm's throw is identical, so any change is the ball dragging on the opening
    fingers.  1 cm/s at release moves the catch point about 0.6 cm."""
    rubber = {(r.approach, r.trial): np.array([r.v_release_true_x, r.v_release_true_y, r.v_release_true_z])
              for r in select_all(results, RUBBER)}
    changes = [np.linalg.norm(np.array([r.v_release_true_x, r.v_release_true_y, r.v_release_true_z]) - rubber[key])
               for r in select_all(results, friction) if (key := (r.approach, r.trial)) in rubber]
    if not changes:
        return "-"
    return f"{100 * np.median(changes):.2f} / {100 * np.max(changes):.2f}"


def select_all(results, friction: float) -> list:
    """Every approach's nominal-noise tosses with this ball."""
    return [r for approach in APPROACHES for r in select(results, approach, friction).results]


def _ends(row: Row) -> str:
    """Where caught balls end along the fingers from the pinch point (cm).  The pad reaches 1 cm."""
    ends = [r.end_fingers for r in row.results if r.caught]
    return f"{100 * np.median(ends):.2f}" if ends else "-"


def _miss(row: Row) -> str:
    return f"{100 * np.nanmedian([r.predicted_miss for r in row.results]):.1f}" if row.results else "-"


def _label(mu: float) -> str:
    return f"{NAME_OF.get(mu, '?')} ({mu:g})"


# ---------- the report ----------

def no_noise_table(results) -> list[str]:
    lines = ["| material (ball-pad friction) | baseline | Approach A | Approach B | ball ends along the fingers, baseline / A / B (cm) |",
             "|---|---|---|---|---|"]
    for mu in FRICTIONS:
        rows = [select(results, approach, mu, noisy=False) for approach in APPROACHES]
        if not any(row.results for row in rows):
            continue
        cells_ = [outcome(row.results[0]) if row.results else "-" for row in rows]
        ends = [f"{100 * row.results[0].end_fingers:.2f}" if row.results else "-" for row in rows]
        lines.append(f"| {_label(mu)} | {' | '.join(cells_)} | {' / '.join(ends)} |")
    return lines


def caught_table(results) -> list[str]:
    lines = ["| material (ball-pad friction) | baseline caught | A caught | B caught | B against A: only B / only A, p |",
             "|---|---|---|---|---|"]
    for mu in FRICTIONS:
        base, a, b = (select(results, approach, mu) for approach in APPROACHES)
        if not (a.results and b.results):
            continue
        lines.append(f"| {_label(mu)} | {base.text() if base.results else '-'} | {a.text()} | {b.text()} | {b.paired(a)} |")
    return lines


def outcome_table(results) -> list[str]:
    lines = ["| material | approach | " + " | ".join(OUTCOMES) + " | caught ball ends along the fingers, median (cm) |",
             "|---|---|" + "---|" * len(OUTCOMES) + "---|"]
    for mu in FRICTIONS:
        for approach, name in APPROACHES.items():
            row = select(results, approach, mu)
            if row.results:
                counts = outcome_counts(row)
                lines.append(f"| {_label(mu)} | {name} | " + " | ".join(str(counts[o]) for o in OUTCOMES) + f" | {_ends(row)} |")
    return lines


def rubber_table(results) -> list[str]:
    lines = ["| material | baseline: lost / gained, p | A: lost / gained, p | B: lost / gained, p | "
             "release velocity change, median / largest (cm/s) | predicted miss, median, A / B (cm) |",
             "|---|---|---|---|---|---|"]
    for mu in FRICTIONS:
        if mu == RUBBER or not select(results, B, mu).results:
            continue
        lines.append(f"| {_label(mu)} | " + " | ".join(against_rubber(results, approach, mu) for approach in APPROACHES)
                     + f" | {release_change(results, mu)} | {_miss(select(results, A, mu))} / {_miss(select(results, B, mu))} |")
    return lines


INTRO = """# The ball's material: a friction sweep

Generated tables are below the marker.  Write the findings here, above it: everything above the marker is kept when the
report is regenerated.

How to read it:

- **Friction** is the coefficient between the ball and the gripper's fingertip pads.  Only friction changes: the ball's
  size, mass and softness are the same in every row.  The values are representative, not measured.
- **Rubber (1.0) is what every earlier result used**, so its row should match `results/robustness.md`'s nominal cell
  (`python robustness_friction.py check`).
- Everything, including the baseline's calibrated target, was tuned on the rubber ball.
- **Lost / gained** compares the same approach on the same 100 tosses with this ball against the rubber one.
- **Gripped, then lost** is the slipping failure: the fingers closed and held the ball, but for under 0.5 s.
- **Release velocity change** is how much the ball dragging on the opening fingers changed the toss, against the rubber
  ball on the same toss.

## Findings

(To write after the sweep.)

"""


def write_report(results, path: Path = REPORT_PATH) -> None:
    """Write the tables below the marker in path, keeping whatever is above it."""
    above = INTRO
    if path.exists() and GENERATED_MARKER in path.read_text():
        above = path.read_text().split(GENERATED_MARKER)[0]
    sections = [
        ("No noise: one toss per material", no_noise_table(results)),
        ("Caught, at the nominal noise", caught_table(results)),
        ("How each toss ended", outcome_table(results)),
        ("Against the rubber ball, on the same tosses", rubber_table(results)),
    ]
    n = len(select(results, B, RUBBER).results) or N_TRIALS
    lines = [GENERATED_MARKER, "",
             f"Every noisy row is the same {n} tosses at sigma_p = 2 mm, sigma lateral = 0.04 m/s, sigma vertical = 0.02 m/s and 30 ms of "
             "close latency, as robustness.md's nominal cell.  Caught is spec section 13.3's definition, with a 95% confidence interval.", ""]
    for title, table in sections:
        lines += [f"## {title}", ""] + table + [""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(above + "\n".join(lines))


# ---------- the check against the robustness sweep ----------

def check(path: Path = CSV_PATH) -> int:
    """The rubber rows should repeat robustness.csv's nominal cell: same catches, and
    the same predictions up to the re-run tolerance in trials.py.  Returns how many
    tosses differ in whether they were caught."""
    mine = read_results(path)
    saved = replan_trials.read_results(robustness.CSV_PATH)
    differ = 0
    for approach, name in APPROACHES.items():
        theirs = {r.trial: r for r in robustness.select(saved, approach).results}
        rows = select(mine, approach, RUBBER).results
        caught = sum(r.caught != theirs[r.trial].caught for r in rows if r.trial in theirs)
        miss = max((abs(r.predicted_miss - theirs[r.trial].predicted_miss) for r in rows if r.trial in theirs), default=float("nan"))
        print(f"{name}: {len(rows)} rubber tosses; {caught} caught differently from robustness.csv; "
              f"largest predicted-miss difference {1e3 * miss:.3f} mm")
        differ += caught
    print("matches robustness.csv" if differ == 0 else f"{differ} tosses differ: look before trusting the sweep")
    return differ


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "all"
    if mode == "pilot":
        run(pilot_grid())
    elif mode == "quick":
        run(grid(QUICK_TRIALS), QUICK_CSV_PATH, QUICK_REPORT_PATH)
    elif mode == "report":
        write_report(read_results(CSV_PATH), REPORT_PATH)
    elif mode == "check":
        check()
    elif mode == "all":
        run(grid())
    else:
        sys.exit(f"unknown mode {mode!r}: use pilot, quick, report, check, or nothing for the full sweep")
