"""The tables of results/robustness.md, drawn as images.

    python tables.py

reads the generated tables out of results/robustness.md and writes one PNG per
table to results/tables/.  The markdown stays the source: nothing here computes a
number, it only renders what robustness.py wrote, so a table and its image cannot
disagree.  Run it after `python robustness.py report`.

The sweep's widest tables are twelve columns with headers like "caught ball ends
along the fingers, median, A / B (cm)", which is what makes them hard to read as
text.  Headers are wrapped rather than truncated, so no column loses its meaning.
"""

from pathlib import Path
import re
import textwrap

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle

from figures import GRID, MUTED, SURFACE, TEXT

SOURCE = Path(__file__).parent / "results" / "robustness.md"
OUT = Path(__file__).parent / "results" / "tables"
MARKER = "<!-- Everything below this line is generated by robustness.py. -->"

FONT_SIZE = 8.5
CHAR_W = FONT_SIZE * 0.6023 / 72  # inches; DejaVu Sans Mono's advance width
LINE_H = FONT_SIZE * 1.45 / 72
PAD_X, PAD_Y = 0.12, 0.06  # inches of padding inside a cell; dense rows need the gap
HEADER_WRAP = 20  # characters before a header wraps
CELL_WRAP = 34  # a data cell may be wider before it wraps
STRIPE = "#f4f3ef"
HEADER_BAND = "#eceae4"


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_rule(line: str) -> bool:
    return bool(re.fullmatch(r"\|[\s:|-]+\|", line.strip()))


def tables(text: str) -> list[tuple[str, list[list[str]]]]:
    """Every markdown table below the marker, as (heading, rows).

    A table belongs to the nearest heading above it; where one heading carries
    several, they are numbered so no image overwrites another.
    """
    found: list[tuple[str, list[list[str]]]] = []
    heading, rows, seen = "table", [], {}

    def flush():
        nonlocal rows
        if rows:
            seen[heading] = seen.get(heading, 0) + 1
            found.append((heading if seen[heading] == 1 else f"{heading} {seen[heading]}", rows))
            rows = []

    for line in text.split(MARKER)[-1].splitlines():
        if line.startswith("#"):
            heading = line.lstrip("#").strip()
        if line.strip().startswith("|"):
            if not _is_rule(line):
                rows.append(_cells(line))
            continue
        flush()
    flush()  # the report ends with a table, so the last one is only ever flushed here
    return found


def _wrapped(rows: list[list[str]]) -> list[list[list[str]]]:
    """Every cell as its list of lines: headers wrap sooner than data."""
    return [[textwrap.wrap(cell, HEADER_WRAP if i == 0 else CELL_WRAP) or [""] for cell in row]
            for i, row in enumerate(rows)]


def slug(heading: str) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", heading.lower())).strip("-") or "table"


def draw(heading: str, rows: list[list[str]], out: Path) -> Path:
    """One table as a PNG: a header band, hairline rules and striped rows."""
    grid = _wrapped(rows)
    columns = max(len(row) for row in rows)
    widths = [max((len(line) for row in grid if i < len(row) for line in row[i]), default=1) * CHAR_W + 2 * PAD_X
              for i in range(columns)]
    heights = [max(len(cell) for cell in row) * LINE_H + 2 * PAD_Y for row in grid]
    title_h = LINE_H * 2.2
    width, height = sum(widths), sum(heights) + title_h

    fig = plt.figure(figsize=(width, height))
    fig.patch.set_facecolor(SURFACE)
    ax = fig.add_axes((0, 0, 1, 1))
    ax.set_xlim(0, width)
    ax.set_ylim(0, height)
    ax.axis("off")

    ax.text(PAD_X, height - LINE_H, heading, color=TEXT, fontsize=FONT_SIZE + 1.5, fontweight="bold",
            va="center", ha="left")

    y = height - title_h
    for r, (row, row_h) in enumerate(zip(grid, heights)):
        y -= row_h
        if r == 0:  # the header sits on a band of its own, so it reads as a header
            ax.add_patch(Rectangle((0, y), width, row_h, facecolor=HEADER_BAND, edgecolor="none", zorder=0))
        elif r % 2 == 0:
            ax.add_patch(Rectangle((0, y), width, row_h, facecolor=STRIPE, edgecolor="none", zorder=0))
        if r == 1:  # the rule under the header
            ax.plot([0, width], [y + row_h, y + row_h], color=MUTED, linewidth=0.9, zorder=2)
        elif r > 1:
            ax.plot([0, width], [y + row_h, y + row_h], color=GRID, linewidth=0.5, zorder=1)
        x = 0.0
        for c in range(columns):
            lines = row[c] if c < len(row) else [""]
            top = y + row_h - PAD_Y
            for i, line in enumerate(lines):
                ax.text(x + PAD_X, top - (i + 0.5) * LINE_H, line, color=TEXT if r == 0 else TEXT,
                        fontsize=FONT_SIZE, fontweight="bold" if r == 0 else "normal", va="center",
                        ha="left", family="monospace", zorder=3)
            x += widths[c]
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=200, facecolor=SURFACE, bbox_inches="tight", pad_inches=0.06)
    plt.close(fig)
    return out


def make_all(source: Path = SOURCE, out_dir: Path = OUT) -> list[Path]:
    found = tables(source.read_text())
    return [draw(heading, rows, out_dir / f"{i:02d}-{slug(heading)}.png")
            for i, (heading, rows) in enumerate(found, start=1)]


if __name__ == "__main__":
    for path in make_all():
        print(path)
