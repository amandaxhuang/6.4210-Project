"""Running trials: the record of one toss and catch, a seeded sweep, and its summary.

A trial's noise depends only on its number, so trial n is the same toss with the
same sensor noise under every approach, and approaches can be compared in pairs.
Trials are simulated in parallel, so each worker writes its SDFs to its own folder.

    HEADLESS=1 python trials.py

runs the grid below, which is what the nominal cell gets chosen from, and writes
results/approach_a.csv and results/approach_a.md.  Text above the marker in the
.md is kept, so interpretation can live there.
"""

import csv
from dataclasses import dataclass, fields
import math
import multiprocessing
import os
from pathlib import Path
import tempfile
import time

os.environ.setdefault("HEADLESS", "1")  # a sweep has nobody watching it
os.environ.setdefault("OMP_NUM_THREADS", "1")  # the workers are the parallelism

import numpy as np
from scipy.stats import binomtest

import catch
import environment as env
import sensing

N_WORKERS = 7
N_TRIALS = 100
CSV_PATH = Path(__file__).parent / "results" / "approach_a.csv"
REPORT_PATH = Path(__file__).parent / "results" / "approach_a.md"
GENERATED_MARKER = "<!-- Everything below this line is generated by trials.py. -->"

# Repeated simulations differ by up to about 1e-12, so results compare within this.
SAME = 1e-9
WALL_CLOCK_COLUMNS = ("solve_time", "wall_time")

# The grid the nominal cell is chosen from.
GRID_SIGMA_P = [0.0, 0.002, 0.003, 0.004, 0.005]  # m
GRID_SIGMA_LAT = [0.02, 0.04, 0.06]  # m/s
GRID_SIGMA_VZ = 0.02  # m/s


@dataclass(frozen=True)
class TrialConfig:
    """One trial of one cell of the experiment.  The defaults are spec section 13.4's nominal cell."""

    approach: str  # a key of catch.POLICIES
    trial: int = 0
    sigma_p: float = sensing.SIGMA_P
    sigma_v: float = sensing.SIGMA_V
    obs_mode: str = sensing.POSITION_ONLY
    sigma_lat: float = 0.02
    sigma_vz: float = 0.02
    latency: float = catch.T_LATENCY
    assumed_latency: float | None = None  # what the trigger allows for, if not the latency itself


@dataclass
class TrialResult:
    """One row of the record: spec section 13.1.  Distances in m, times in s."""

    approach: str
    trial: int
    seed: int
    sigma_p: float
    sigma_v: float
    obs_mode: str
    sigma_lat: float
    sigma_vz: float
    latency: float
    caught: bool  # spec section 13.3: both fingers and grip force for HOLD_TIME
    caught_on_pad: bool  # and the ball's center ends on the pads, not perched on their edges
    contact: bool
    hold_time: float
    miss_horizontal: float  # ball to pinch point as the ball crosses the catch plane
    miss_vertical: float
    miss_closing: float  # the same miss in the gripper frame
    miss_fingers: float
    miss_across: float
    end_fingers: float  # where the ball ends up relative to the pinch point
    end_across: float
    timing_error: float  # real crossing of the catch plane - planned
    predicted_miss: float  # the estimator's error alone
    arm_arrival_error: float  # the tracker's error alone
    solve_ok: bool
    solve_time: float
    wall_time: float
    n_solves: int
    policy_calls: int
    plans_adopted: int
    fit_rank_deficient: bool
    intercept_rejected: bool
    p_release_true_x: float  # what the toss really did, referred to the release time
    p_release_true_y: float
    p_release_true_z: float
    v_release_true_x: float
    v_release_true_y: float
    v_release_true_z: float
    assumed_latency: float | None = None


def release_state(run) -> tuple[np.ndarray, np.ndarray]:
    """The flight the ball really took, after any toss noise, as a position and a
    velocity at the release time."""
    log, t_release = run.log, run.toss_plan.t_release
    i = np.searchsorted(log.t, t_release + catch.T_TOSS_NOISE + 0.002)
    tau = log.t[i] - t_release
    v0 = log.ball_v[i] - sensing.GRAVITY * tau
    return log.ball_p[i] - v0 * tau - 0.5 * sensing.GRAVITY * tau**2, v0


def run_trial(config: TrialConfig) -> TrialResult:
    start = time.perf_counter()
    run = catch.simulate_catch(catch.POLICIES[config.approach], sigma_p=config.sigma_p, sigma_v=config.sigma_v,
                               obs_mode=config.obs_mode, latency=config.latency, assumed_latency=config.assumed_latency,
                               sigma_lat=config.sigma_lat, sigma_vz=config.sigma_vz, trial=config.trial)
    wall_time = time.perf_counter() - start
    o, plan = run.outcome, run.plans[-1]
    p0, v0 = release_state(run)
    return TrialResult(
        approach=config.approach, trial=config.trial, seed=catch.SEED_ROOT, sigma_p=config.sigma_p,
        sigma_v=config.sigma_v, obs_mode=config.obs_mode, sigma_lat=config.sigma_lat, sigma_vz=config.sigma_vz,
        latency=config.latency, assumed_latency=config.assumed_latency, caught=bool(o.caught),
        caught_on_pad=bool(o.caught) and catch.ball_on_pad(o.end_in_hand), contact=bool(o.contact),
        hold_time=float(o.hold_time), miss_horizontal=float(o.miss_horizontal), miss_vertical=float(o.miss_vertical),
        miss_closing=float(o.miss_in_hand[0]), miss_fingers=float(o.miss_in_hand[1]), miss_across=float(o.miss_in_hand[2]),
        end_fingers=float(o.end_in_hand[1]), end_across=float(o.end_in_hand[2]), timing_error=float(o.timing_error),
        predicted_miss=float(o.predicted_miss), arm_arrival_error=float(o.arm_arrival_error), solve_ok=bool(plan.solve_ok),
        solve_time=float(sum(p.solve_time for p in run.plans)), wall_time=wall_time, n_solves=len(run.plans),
        policy_calls=run.controller.policy_calls, plans_adopted=run.controller.plans_adopted,
        fit_rank_deficient=bool(plan.fit_rank_deficient), intercept_rejected=bool(plan.intercept_rejected),
        p_release_true_x=float(p0[0]), p_release_true_y=float(p0[1]), p_release_true_z=float(p0[2]),
        v_release_true_x=float(v0[0]), v_release_true_y=float(v0[1]), v_release_true_z=float(v0[2]),
    )


def _init_worker():
    # make_scenario rewrites the SDFs on every run, so each worker needs its own.
    env.ASSET_DIR = Path(tempfile.mkdtemp(prefix="trials_"))


def sweep(configs: list[TrialConfig], n_workers: int = N_WORKERS) -> list[TrialResult]:
    """Run the trials in parallel.  Results come back in the order of configs."""
    with multiprocessing.get_context("spawn").Pool(n_workers, initializer=_init_worker) as pool:
        return pool.map(run_trial, configs, chunksize=1)


def write_csv(results: list[TrialResult], path: Path) -> None:
    names = [f.name for f in fields(TrialResult)]

    def cell(value):
        return f"{value:.12g}" if isinstance(value, float) else str(value)

    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(names)
        for r in results:
            writer.writerow([cell(getattr(r, name)) for name in names])


def read_csv(path: Path) -> list[dict[str, str]]:
    with open(path, newline="") as file:
        return list(csv.DictReader(file))


def _same(a: str, b: str, tolerance: float) -> bool:
    if a == b:
        return True
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    return (math.isnan(x) and math.isnan(y)) or abs(x - y) <= tolerance


def csv_differences(path_a: Path, path_b: Path, tolerance: float = SAME, ignore=WALL_CLOCK_COLUMNS) -> list[str]:
    """What differs between two result files, or nothing if they reproduce each
    other.  This takes a tolerance rather than comparing text, because a value near
    a rounding boundary can flip its last digit however it is rounded."""
    a, b = read_csv(path_a), read_csv(path_b)
    if len(a) != len(b):
        return [f"{len(a)} rows against {len(b)}"]
    return [f"row {i}, {name}: {x[name]} against {y[name]}"
            for i, (x, y) in enumerate(zip(a, b)) for name in x
            if name not in ignore and not _same(x[name], y[name], tolerance)]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% confidence interval on a proportion of k out of n."""
    if n == 0:
        return 0.0, 1.0
    p = k / n
    center = (p + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * math.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return (0.0 if k == 0 else center - half), (1.0 if k == n else center + half)


def mcnemar(a, b) -> tuple[int, int, float]:
    """Compare paired outcomes.  Returns how many only a got, how many only b got,
    and the exact two-sided p-value that they differ."""
    only_a = sum(x and not y for x, y in zip(a, b))
    only_b = sum(y and not x for x, y in zip(a, b))
    if only_a + only_b == 0:
        return 0, 0, 1.0
    return only_a, only_b, float(binomtest(only_a, only_a + only_b, 0.5).pvalue)


@dataclass
class CellSummary:
    """One cell's results."""

    approach: str
    sigma_p: float
    sigma_lat: float
    sigma_vz: float
    latency: float
    n: int
    caught: int
    on_pad: int
    contact: int
    no_plan: int
    rejected: int
    predicted_median: float
    arrival_median: float
    timing_sigma: float
    only_this: int | None = None  # paired with the baseline at the same toss noise, on caught
    only_baseline: int | None = None
    paired_p: float | None = None


def summarize(results: list[TrialResult]) -> list[CellSummary]:
    """Summarize each cell, in the order the cells first appear."""
    cells: dict[tuple, list[TrialResult]] = {}
    for r in results:
        cells.setdefault((r.approach, r.sigma_p, r.sigma_lat, r.sigma_vz, r.latency), []).append(r)
    summaries = []
    for (approach, sigma_p, sigma_lat, sigma_vz, latency), rows in cells.items():
        planned = [r.arm_arrival_error for r in rows if r.solve_ok]
        summary = CellSummary(
            approach, sigma_p, sigma_lat, sigma_vz, latency, len(rows), sum(r.caught for r in rows),
            sum(r.caught_on_pad for r in rows), sum(r.contact for r in rows), sum(not r.solve_ok for r in rows),
            sum(r.intercept_rejected for r in rows), float(np.nanmedian([r.predicted_miss for r in rows])),
            float(np.median(planned)) if planned else math.nan, float(np.nanstd([r.timing_error for r in rows])))
        baseline = {r.trial: r.caught for key, group in cells.items()
                    if key[0] == "open_loop" and key[2:] == (sigma_lat, sigma_vz, latency) for r in group}
        paired = [r for r in rows if r.trial in baseline]
        if approach != "open_loop" and paired:
            summary.only_this, summary.only_baseline, summary.paired_p = mcnemar(
                [r.caught for r in paired], [baseline[r.trial] for r in paired])
        summaries.append(summary)
    return summaries


def _rate(k: int, n: int) -> str:
    low, high = wilson(k, n)
    return f"{k} / {n} ({100 * low:.0f}–{100 * high:.0f}%)"


def write_report(results: list[TrialResult], path: Path) -> None:
    """Write the summary below the marker in path, keeping whatever is above it."""
    above = "# Approach A and the baseline\n\n"
    if path.exists():
        above = path.read_text().split(GENERATED_MARKER)[0]
    lines = [GENERATED_MARKER, "",
             "Caught is spec section 13.3's definition, with a 95% confidence interval. On pad also needs the ball's "
             "center to end on the 2 cm square pads. 'vs baseline' compares the same tosses: how many only this row "
             "caught, how many only the baseline caught, and McNemar's exact p.", "",
             "| approach | sigma_p (mm) | sigma lateral (m/s) | sigma vertical (m/s) | caught | on pad | contact | no plan "
             "| rejected | predicted miss, median (cm) | arm arrival error, median (cm) | timing error, 1 sigma (ms) | vs baseline |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in summarize(results):
        name = "baseline" if c.approach == "open_loop" else "Approach A"
        sensor = "-" if c.approach == "open_loop" else f"{1e3 * c.sigma_p:.0f}"
        versus = "-" if c.paired_p is None else f"{c.only_this} / {c.only_baseline}, p = {c.paired_p:.2g}"
        lines.append(f"| {name} | {sensor} | {c.sigma_lat} | {c.sigma_vz} | {_rate(c.caught, c.n)} | {c.on_pad} | {c.contact} | "
                     f"{c.no_plan} | {c.rejected} | {100 * c.predicted_median:.1f} | {100 * c.arrival_median:.2f} | "
                     f"{1e3 * c.timing_sigma:.1f} | {versus} |")
    wall = [r.wall_time for r in results]
    lines += ["", f"{len(results)} trials, {np.mean(wall):.1f} s per trial on average per worker, "
                  f"{np.mean([r.solve_time for r in results]):.2f} s of that solving.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(above + "\n".join(lines))


def grid() -> list[TrialConfig]:
    """The baseline and Approach A across sensor and toss noise, and the noiseless
    cell the proposal's goal is stated against."""
    configs = []
    for approach in ("open_loop", "predict_once"):
        configs += [TrialConfig(approach, trial=t, sigma_p=0.0, sigma_lat=0.0, sigma_vz=0.0) for t in range(N_TRIALS)]
    for sigma_lat in GRID_SIGMA_LAT:
        configs += [TrialConfig("open_loop", trial=t, sigma_p=0.0, sigma_lat=sigma_lat, sigma_vz=GRID_SIGMA_VZ)
                    for t in range(N_TRIALS)]
        for sigma_p in GRID_SIGMA_P:
            configs += [TrialConfig("predict_once", trial=t, sigma_p=sigma_p, sigma_lat=sigma_lat, sigma_vz=GRID_SIGMA_VZ)
                        for t in range(N_TRIALS)]
    return configs


def run():
    results = sweep(grid())
    write_csv(results, CSV_PATH)
    write_report(results, REPORT_PATH)
    print(f"{len(results)} trials written to {CSV_PATH} and {REPORT_PATH}")


if __name__ == "__main__":
    run()
